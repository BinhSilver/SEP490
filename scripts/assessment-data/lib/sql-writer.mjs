import crypto from "node:crypto";

export function sqlString(value) {
  if (value === null || value === undefined || value === "") return "NULL";
  return `'${String(value).replaceAll("\\", "\\\\").replaceAll("'", "''").replaceAll("\0", "\\0")}'`;
}

export function sqlBoolean(value) {
  return value === true || String(value ?? "").trim().toUpperCase() === "TRUE" || String(value) === "1" ? "1" : "0";
}

export function sqlNumber(value, fallback = 0) {
  const number = Number(value);
  if (!Number.isFinite(number)) return String(fallback);
  return String(number);
}

export function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

export function sqlHeader(label) {
  return `-- Generated by J-LAS assessment data pipeline: ${label}\nSET NAMES utf8mb4;\nSTART TRANSACTION;\n`;
}

export function sqlFooter() {
  return "COMMIT;\n";
}
