export function escapeSqlString(value) {
  return String(value ?? "").replaceAll("'", "''");
}

export function sqlString(value) {
  return value === null || value === undefined || value === ""
    ? "NULL"
    : `'${escapeSqlString(value)}'`;
}

export function sqlNumber(value, fallback = "NULL") {
  if (value === null || value === undefined || value === "") return fallback;
  const parsed = Number(value);
  if (!Number.isFinite(parsed)) throw new TypeError(`Expected numeric SQL value, received: ${value}`);
  return String(parsed);
}

export function sqlBoolean(value, fallback = 0) {
  if (value === null || value === undefined || value === "") return String(fallback);
  return [true, 1, "1", "YES", "TRUE"].includes(typeof value === "string" ? value.toUpperCase() : value) ? "1" : "0";
}

export function sqlHeader(title) {
  return `-- Generated by scripts/learning-data/generate-learning-seed.mjs\n-- ${title}\n-- Do not edit generated rows by hand.\n\nSET NAMES utf8mb4;\n\n`;
}

export function upsert(table, columns, values, updates) {
  const updateSql = updates.map((column) => `${column}=VALUES(${column})`).join(", ");
  return `INSERT INTO ${table} (${columns.join(", ")})\nVALUES (${values.join(", ")})\nON DUPLICATE KEY UPDATE ${updateSql};\n`;
}
