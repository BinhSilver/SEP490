"""Generate a deterministic SQL catalog; JSON is build input only, never a runtime dependency.

python tools/generate_kanji_map_seed.py
Apply jlas_schema.sql (fresh DB) or sql/migrations/055_kanji_map_update.sql (existing DB), then the generated SQL.
Only source catalog tables are refreshed. Editorial content and mastery are never touched.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/kanji-map/graph.json'
OUTPUT = ROOT / 'sql/seeds/kanji_map_update.sql'
CHILDREN = ('kanji_map_reading', 'kanji_map_gloss', 'kanji_map_radical_alias',
            'kanji_map_component', 'kanji_map_stroke')


def literal(value):
    # The generated file explicitly enables NO_BACKSLASH_ESCAPES for exact UTF-8 round trips.
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("'", "''") + "'"


def insert(table, columns, rows, update_columns=()):
    result = []
    for start in range(0, len(rows), 100):
        suffix = ' ON DUPLICATE KEY UPDATE ' + ','.join(c + '=VALUES(' + c + ')' for c in update_columns) if update_columns else ''
        result.append('INSERT INTO ' + table + ' (' + ','.join(columns) + ') VALUES\n' +
                      ',\n'.join('(' + ','.join(literal(v) for v in row) + ')' for row in rows[start:start + 100]) + suffix + ';')
    return result


def generate(source=SOURCE, output=OUTPUT):
    raw = source.read_bytes()
    graph = json.loads(raw)
    nodes = graph['nodes']
    by_character = {n['character']: n for n in nodes}
    if len(nodes) != len(by_character) or len(nodes) != graph['counts']['nodes']:
        raise ValueError('Duplicate characters or incorrect node count')
    required = {'character', 'isKanji', 'isRadical', 'radicalNumber', 'level', 'hanViet', 'meaningsEn',
                'meaningVi', 'meaningViSource', 'meaningViSourceUrl', 'memoryHint', 'on', 'kun',
                'strokeCount', 'components', 'contained', 'strokes', 'parent'}
    optional = {'parentRelation', 'radicalNameVi', 'radicalAliases', 'radicalBase', 'isRadicalVariant'}
    for node in nodes:
        if not required <= node.keys() or node.keys() - required - optional:
            raise ValueError('Unsupported node fields: ' + node['character'])
        for field in ('parent', 'radicalBase'):
            if node.get(field) and node[field] not in by_character:
                raise ValueError('Unresolved node reference: ' + node['character'])
        if node['isKanji'] and not node['meaningVi']:
            raise ValueError('Missing Vietnamese meaning: ' + node['character'])
        for component in node['components']:
            if component.keys() != {'character', 'original', 'position', 'partial', 'radical'} or component['character'] not in by_character:
                raise ValueError('Unresolved component: ' + node['character'])

    lines = ['-- [JLAS-KANJI-MAP] GENERATED by tools/generate_kanji_map_seed.py; do not edit by hand.',
             '-- Source: data/kanji-map/graph.json. Run after current schema / sql/migrations/055_kanji_map_update.sql.',
             '-- Unused contained elements and component radical tags stay archived in the source JSON only.',
             '-- Re-runnable. Does not modify kanji_map_content, user_kanji_mastery or dictionary tables.',
             '-- Run the ENTIRE file in one session. No USE statement: select the intended database first.',
             'SET NAMES utf8mb4;', 'SET @kanji_map_previous_sql_mode = @@SESSION.sql_mode;',
             "SET SESSION sql_mode = 'NO_BACKSLASH_ESCAPES,STRICT_TRANS_TABLES,NO_ENGINE_SUBSTITUTION';",
             'START TRANSACTION;', 'UPDATE kanji_map_node SET is_active=FALSE WHERE is_active=TRUE;']
    columns = ['kanji_character', 'source_order', 'is_active', 'is_kanji', 'is_radical', 'radical_number',
               'jlpt_level', 'han_viet', 'meaning_vi', 'meaning_vi_source', 'meaning_vi_source_url',
               'memory_hint', 'stroke_count', 'parent_relation', 'radical_name_vi', 'is_radical_variant']
    rows = []
    for order, node in enumerate(nodes):
        row = [node['character'], order, True, node['isKanji'], node['isRadical'], node['radicalNumber'],
               node['level'], node['hanViet'], node['meaningVi'], node['meaningViSource'], node['meaningViSourceUrl'],
               node['memoryHint'], node['strokeCount'], node.get('parentRelation'), node.get('radicalNameVi'), node.get('isRadicalVariant', False)]
        rows.append(row)
    lines += insert('kanji_map_node', columns, rows, columns[1:])
    # Every referenced glyph now exists, including forward references and variants.
    for start in range(0, len(nodes), 100):
        batch = nodes[start:start + 100]
        assignments = []
        for column, field in [('parent_character', 'parent'), ('radical_base', 'radicalBase')]:
            assignments.append(column + '=CASE kanji_character ' + ' '.join(
                'WHEN ' + literal(n['character']) + ' THEN ' + literal(n.get(field)) for n in batch) + ' END')
        lines.append('UPDATE kanji_map_node SET ' + ','.join(assignments) +
                     ' WHERE kanji_character IN (' + ','.join(literal(n['character']) for n in batch) + ');')
    for table in CHILDREN:
        # Correlate on the indexed glyph key; do not rebuild the entire active set for each deleted row.
        lines.append('DELETE FROM ' + table + ' WHERE EXISTS (SELECT 1 FROM kanji_map_node n WHERE n.kanji_character=' + table + '.kanji_character AND n.is_active=TRUE);')
    lines += insert('kanji_map_reading', ['kanji_character', 'reading_type', 'reading_order', 'reading_text'],
                    [(n['character'], kind, i, text) for n in nodes for kind, field in [('ON', 'on'), ('KUN', 'kun')] for i, text in enumerate(n[field])])
    for table, column, field, order_column in [
        ('kanji_map_gloss', 'meaning_en', 'meaningsEn', 'gloss_order'),
        ('kanji_map_radical_alias', 'alias_text', 'radicalAliases', 'alias_order'),
        ('kanji_map_stroke', 'path_data', 'strokes', 'stroke_order')]:
        lines += insert(table, ['kanji_character', order_column, column],
                        [(n['character'], i, text) for n in nodes for i, text in enumerate(n.get(field, []))])
    lines += insert('kanji_map_component', ['kanji_character', 'component_order', 'component_character', 'original_character', 'position_code', 'is_partial'],
                    [(n['character'], i, c['character'], c['original'], c['position'], c['partial']) for n in nodes for i, c in enumerate(n['components'])])
    sources = json.dumps(graph['sources'], ensure_ascii=False, separators=(',', ':'))
    metadata = [1, graph['version'], hashlib.sha256(raw).hexdigest(), sources, len(nodes)]
    lines += ['INSERT INTO kanji_map_dataset(id,graph_version,source_sha256,sources_json,node_count) VALUES (' +
              ','.join(literal(v) for v in metadata) + ') ON DUPLICATE KEY UPDATE graph_version=VALUES(graph_version),'
              'source_sha256=VALUES(source_sha256),sources_json=VALUES(sources_json),node_count=VALUES(node_count);',
              'COMMIT;', 'SET SESSION sql_mode = @kanji_map_previous_sql_mode;', '']
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='utf-8', newline='\n') as stream:
        stream.write('\n\n'.join(lines).rstrip('\n') + '\n')
    return len(nodes)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=SOURCE)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    count = generate(args.source, args.output)
    print(f'Generated {args.output} with {count} catalog nodes; editorial content and progress excluded.')
