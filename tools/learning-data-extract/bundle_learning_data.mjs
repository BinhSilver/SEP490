// [JLAS-W0108] Owner 2026-11-07: the Learning data ships as ONE file, sql/learning/learning_data.sql (Git LFS), run after
// sql/learning/learning_schema.sql. The builders keep writing their blocks into the per-part working files under
// sql/learning/parts/ (not tracked); this tool joins the parts into the shipped file and splits it back.
//
//   node tools/learning-data-extract/bundle_learning_data.mjs           # parts -> learning_data.sql
//   node tools/learning-data-extract/bundle_learning_data.mjs --check   # exit 1 when learning_data.sql differs from the parts
//   node tools/learning-data-extract/bundle_learning_data.mjs --split   # learning_data.sql -> parts (before running a builder)
//
// Run order inside the file: common, N5, N4, N3, N2, N1 (a level reads rows of lower levels only), then the
// communication path. Each part is kept byte for byte between `-- ==== PART <name> BEGIN ====` / `END` lines.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PARTS = ['learning_data_common.sql', 'learning_data_N5.sql', 'learning_data_N4.sql', 'learning_data_N3.sql',
  'learning_data_N2.sql', 'learning_data_N1.sql', 'learning_data_comm.sql'];
const begin = (name) => `-- ==== PART ${name} BEGIN ====`;
const end = (name) => `-- ==== PART ${name} END ====`;

export function bundleFile(root) { return path.join(root, 'sql/learning/learning_data.sql'); }
export function partsDir(root) { return path.join(root, 'sql/learning/parts'); }

const HEADER = '-- [JLAS-W0108] Learning flow data (JLPT path N5-N1, communication path). Generated by\n'
  + '-- tools/learning-data-extract/bundle_learning_data.mjs from sql/learning/parts/; do not edit by hand.\n'
  + '-- Run after sql/learning/learning_schema.sql on the target database. Re-runnable (upserts by stable keys).\n';

/** `DROP TEMPORARY TABLE IF EXISTS` for every temporary table a part creates (empty when it creates none). */
export function dropTemps(body) {
  const names = [...new Set([...body.toString('latin1').matchAll(/CREATE TEMPORARY TABLE (?:IF NOT EXISTS )?`?(\w+)`?/gi)].map((m) => m[1]))];
  return names.length ? `DROP TEMPORARY TABLE IF EXISTS ${names.join(', ')};\n` : '';
}

/** Joins the parts (Buffers keep each part's bytes and newline style). */
export function bundle(root) {
  const chunks = [Buffer.from(HEADER, 'utf8')];
  for (const name of PARTS) {
    const file = path.join(partsDir(root), name);
    if (!fs.existsSync(file)) throw new Error(`Missing part ${path.relative(root, file)}; run with --split first`);
    const body = fs.readFileSync(file);
    chunks.push(Buffer.from(`\n${begin(name)}\n`, 'utf8'), body);
    if (body.length && body[body.length - 1] !== 0x0a) chunks.push(Buffer.from('\n', 'utf8'));
    // one file = one MySQL session: drop the part's temporary tables so a later part can create its own
    chunks.push(Buffer.from(`${dropTemps(body)}${end(name)}\n`, 'utf8'));
  }
  return Buffer.concat(chunks);
}

/** Splits the shipped file back into the parts (exact inverse of bundle for parts that end with a newline). */
export function split(root) {
  const text = fs.readFileSync(bundleFile(root)).toString('latin1'); // byte-preserving
  fs.mkdirSync(partsDir(root), { recursive: true });
  for (const name of PARTS) {
    const b = text.indexOf(`${begin(name)}\n`);
    const e = text.indexOf(`${end(name)}\n`, b);
    if (b < 0 || e < 0) throw new Error(`learning_data.sql has no part ${name}`);
    let body = text.slice(b + begin(name).length + 1, e);
    const drop = /DROP TEMPORARY TABLE IF EXISTS [^\n]*;\n$/.exec(body);
    if (drop && dropTemps(Buffer.from(body.slice(0, drop.index), 'latin1')) === drop[0]) body = body.slice(0, drop.index);
    fs.writeFileSync(path.join(partsDir(root), name), Buffer.from(body, 'latin1'));
  }
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const arg = process.argv[2] || '';
  if (arg === '--split') { split(root); console.log(`Split ${PARTS.length} parts into sql/learning/parts/`); return; }
  const out = bundle(root);
  if (arg === '--check') {
    const ok = fs.existsSync(bundleFile(root)) && fs.readFileSync(bundleFile(root)).equals(out);
    console.log(ok ? 'learning_data.sql matches the parts.' : 'learning_data.sql is stale: run bundle_learning_data.mjs');
    if (!ok) process.exitCode = 1;
    return;
  }
  fs.writeFileSync(bundleFile(root), out);
  console.log(`Wrote sql/learning/learning_data.sql (${(out.length / 1048576).toFixed(1)} MiB, ${PARTS.length} parts)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
