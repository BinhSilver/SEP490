// [JLAS-W0108] Owner 2026-11-07: the Learning data ships as six files in Git LFS, run after
// sql/learning/learning_schema.sql in this order:
//   learning_data_N5.sql (the common data first, then N5) -> N4 -> N3 -> N2 -> N1 -> learning_data_comm.sql
// The seed builders keep writing their blocks into the per-part working files under sql/learning/parts/ (not tracked);
// this tool writes the shipped files from the parts and splits them back.
//
//   node tools/learning-data-extract/bundle_learning_data.mjs           # parts -> the six shipped files
//   node tools/learning-data-extract/bundle_learning_data.mjs --check   # exit 1 when a shipped file differs from the parts
//   node tools/learning-data-extract/bundle_learning_data.mjs --split   # shipped files -> parts (before running a builder)
//
// Each part is kept byte for byte between `-- ==== PART <name> BEGIN ====` / `END` lines, and drops its temporary tables
// at its end, so two parts in one file (N5) run in one MySQL session.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Shipped file -> the parts it holds, in run order. */
export const FILES = [
  ['learning_data_N5.sql', ['learning_data_common.sql', 'learning_data_N5.sql']],
  ['learning_data_N4.sql', ['learning_data_N4.sql']],
  ['learning_data_N3.sql', ['learning_data_N3.sql']],
  ['learning_data_N2.sql', ['learning_data_N2.sql']],
  ['learning_data_N1.sql', ['learning_data_N1.sql']],
  ['learning_data_comm.sql', ['learning_data_comm.sql', 'learning_data_comm_core.sql']],
];
const begin = (name) => `-- ==== PART ${name} BEGIN ====`;
const end = (name) => `-- ==== PART ${name} END ====`;

export function shippedDir(root) { return path.join(root, 'sql/learning'); }
export function partsDir(root) { return path.join(root, 'sql/learning/parts'); }

function header(file, parts) {
  return `-- [JLAS-W0108] Learning flow data: ${file} (${parts.map((p) => p.replace(/^learning_data_|\.sql$/g, '')).join(' + ')}).\n`
    + '-- Generated by tools/learning-data-extract/bundle_learning_data.mjs from sql/learning/parts/; do not edit by hand.\n'
    + '-- Run after sql/learning/learning_schema.sql: N5, N4, N3, N2, N1, then comm. Re-runnable (upserts by stable keys).\n';
}

/** `DROP TEMPORARY TABLE IF EXISTS` for every temporary table a part creates (empty when it creates none). */
export function dropTemps(body) {
  const names = [...new Set([...body.toString('latin1').matchAll(/CREATE TEMPORARY TABLE (?:IF NOT EXISTS )?`?(\w+)`?/gi)].map((m) => m[1]))];
  return names.length ? `DROP TEMPORARY TABLE IF EXISTS ${names.join(', ')};\n` : '';
}

/** One shipped file from its parts (Buffers keep each part's bytes and newline style). */
export function build(root, file, parts) {
  const chunks = [Buffer.from(header(file, parts), 'utf8')];
  for (const name of parts) {
    const p = path.join(partsDir(root), name);
    if (!fs.existsSync(p)) throw new Error(`Missing part ${path.relative(root, p)}; run with --split first`);
    const body = fs.readFileSync(p);
    chunks.push(Buffer.from(`\n${begin(name)}\n`, 'utf8'), body);
    if (body.length && body[body.length - 1] !== 0x0a) chunks.push(Buffer.from('\n', 'utf8'));
    chunks.push(Buffer.from(`${dropTemps(body)}${end(name)}\n`, 'utf8'));
  }
  return Buffer.concat(chunks);
}

/** Splits the shipped files back into the parts (exact inverse of build for parts that end with a newline). */
export function split(root) {
  fs.mkdirSync(partsDir(root), { recursive: true });
  for (const [file, parts] of FILES) {
    const text = fs.readFileSync(path.join(shippedDir(root), file)).toString('latin1'); // byte-preserving
    for (const name of parts) {
      const b = text.indexOf(`${begin(name)}\n`);
      const e = text.indexOf(`${end(name)}\n`, b);
      if (b < 0 || e < 0) throw new Error(`${file} has no part ${name}`);
      let body = text.slice(b + begin(name).length + 1, e);
      const drop = /DROP TEMPORARY TABLE IF EXISTS [^\n]*;\n$/.exec(body);
      if (drop && dropTemps(Buffer.from(body.slice(0, drop.index), 'latin1')) === drop[0]) body = body.slice(0, drop.index);
      fs.writeFileSync(path.join(partsDir(root), name), Buffer.from(body, 'latin1'));
    }
  }
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const arg = process.argv[2] || '';
  if (arg === '--split') { split(root); console.log('Split the shipped files into sql/learning/parts/'); return; }
  let stale = 0;
  for (const [file, parts] of FILES) {
    const out = build(root, file, parts);
    const target = path.join(shippedDir(root), file);
    if (arg === '--check') {
      const ok = fs.existsSync(target) && fs.readFileSync(target).equals(out);
      if (!ok) { stale++; console.log(`${file} is stale: run bundle_learning_data.mjs`); }
    } else {
      fs.writeFileSync(target, out);
      console.log(`Wrote sql/learning/${file} (${(out.length / 1048576).toFixed(1)} MiB)`);
    }
  }
  if (arg === '--check') {
    console.log(stale ? `${stale} shipped file(s) stale` : 'All shipped files match the parts.');
    if (stale) process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
