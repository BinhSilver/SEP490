INSERT IGNORE INTO video_tag (video_id, tag_id)
SELECT v.id, t.id
FROM tmp_shadowing_genre g
JOIN video v ON v.source_url = g.source_url
JOIN tag t ON t.code = g.code
WHERE NOT EXISTS (SELECT 1 FROM video_tag x JOIN tag y ON y.id = x.tag_id
                  WHERE x.video_id = v.id AND LEFT(y.code, 12) = 'VIDEO_GENRE_');

