DROP TEMPORARY TABLE IF EXISTS seed_dict_resolved;
CREATE TEMPORARY TABLE seed_dict_resolved AS
SELECT s.seq, s.target_type, s.content, s.days_ago, u.id AS user_id,
       CASE WHEN s.target_type = 'VOCABULARY' THEN
           (SELECT v.id FROM vocabulary_entry v
             WHERE v.normalized_expression = s.expr COLLATE utf8mb4_0900_as_cs
               AND v.normalized_reading = s.reading COLLATE utf8mb4_0900_as_cs
               AND v.dictionary_status = 'PUBLISHED' AND v.usage_scope <> 'TEXTBOOK'
             ORDER BY v.usage_scope = 'BOTH' DESC, v.id LIMIT 1)
       ELSE (SELECT k.id FROM kanji k WHERE k.`character` = s.expr COLLATE utf8mb4_bin LIMIT 1) END AS target_id
FROM seed_dict_comment s
JOIN users u ON u.username = s.username AND u.locked_at IS NULL;

INSERT INTO content_comment (target_type, target_id, user_id, content, is_hidden, created_at, updated_at)
SELECT r.target_type, r.target_id, r.user_id, r.content, 0,
       NOW(6) - INTERVAL r.days_ago DAY - INTERVAL r.seq * 7 MINUTE,
       NOW(6) - INTERVAL r.days_ago DAY - INTERVAL r.seq * 7 MINUTE
FROM seed_dict_resolved r
WHERE r.target_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM content_comment c
                   WHERE c.target_type = r.target_type AND c.target_id = r.target_id
                     AND c.user_id = r.user_id AND c.content = r.content)
ORDER BY r.seq;

INSERT IGNORE INTO content_comment_vote (comment_id, user_id, vote, created_at)
SELECT c.id, u.id, v.vote, c.created_at + INTERVAL (v.seq % 5 + 1) HOUR
FROM seed_dict_vote v
JOIN seed_dict_resolved r ON r.seq = v.seq AND r.target_id IS NOT NULL
JOIN content_comment c ON c.target_type = r.target_type AND c.target_id = r.target_id
                      AND c.user_id = r.user_id AND c.content = r.content
JOIN users u ON u.username = v.username AND u.locked_at IS NULL;

SELECT target_type, COUNT(*) AS seeded_comments FROM content_comment
WHERE target_type IN ('VOCABULARY', 'KANJI') GROUP BY target_type;

