package com.jlas.learning.service.impl;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.HashMap;
import java.util.Map;
import java.util.stream.Collectors;
import java.util.stream.StreamSupport;

/** [JLAS-W0108] Owner 2026-10-21 (OD-13): a Kanji's meaning is its Hán Việt plus the KANJIDIC2 English meanings,
 * credited in place. Learning's own copy ({@code learning/kanji-gloss.json}, generated by
 * {@code tools/learning-data-extract/build_kanji_gloss.mjs}) because the shared {@code kanji} table has no English column. */
@Component
public class KanjiGlossCatalog {
    static final String RESOURCE = "learning/kanji-gloss.json";
    private final Map<String, String> meanings;
    private final String attribution;

    public KanjiGlossCatalog() {
        try (InputStream in = KanjiGlossCatalog.class.getClassLoader().getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IllegalStateException("Missing " + RESOURCE);
            JsonNode root = new ObjectMapper().readTree(in);
            Map<String, String> byKanji = new HashMap<>();
            root.path("kanji").fields().forEachRemaining(entry -> byKanji.put(entry.getKey(),
                    StreamSupport.stream(entry.getValue().spliterator(), false).map(JsonNode::asText)
                            .collect(Collectors.joining("; "))));
            meanings = Map.copyOf(byKanji);
            JsonNode credit = root.path("attribution");
            attribution = "Nghĩa tiếng Anh: " + credit.path("source").asText() + " (" + credit.path("publisher").asText()
                    + "), " + credit.path("license").asText() + ". Cấp JLPT theo danh sách J. Waller (OpenJLPT), chưa kiểm chứng.";
        } catch (IOException exception) {
            throw new UncheckedIOException(exception);
        }
    }

    /** "one; one radical (no.1)", or null when the character has no JLPT-levelled entry. */
    public String meaningEn(String character) {
        return character == null ? null : meanings.get(character);
    }

    public String attribution() {
        return attribution;
    }
}
