package com.jlas.assessment.service.impl;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.jlas.assessment.dto.JlptExamResponse;
import java.io.IOException;
import java.util.LinkedHashMap;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;

/** Resolves question MP3s independently of the legacy remote URLs in the database. */
@Component
public class JlptLocalAudio {
    private static final Pattern SPEAKER = Pattern.compile("(?im)^(narrator|man|woman)(\\d*)\\s*[:：]\\s*");
    private final Map<String, Map<String, LocalClip>> exams = new ConcurrentHashMap<>();
    private final ObjectMapper mapper = new ObjectMapper();

    record LocalClip(String url, double duration, String ja, String vi,
                     List<JlptExamResponse.TranscriptSegment> timedScript) {}

    public JlptExamResponse.AudioClip resolve(String exam, int mondai, int question,
            long questionId, JlptExamResponse.AudioClip previous) {
        if (exam == null || !exam.matches("N[1-5]_[A-Z0-9_]+")) return previous;
        LocalClip local = exams.computeIfAbsent(exam, this::load).get(mondai + ":" + question);
        if (local == null) return previous;
        // Timed scripts are generated by matching the actual MP3 signal to its
        // reference audio, independently of inferred database clip boundaries.
        String ja = prompt(local.ja(), true);
        String vi = prompt(local.vi(), false);
        if (previous != null) {
            if (ja.isBlank()) {
                ja = previous.transcript().stream().map(s -> s.ja() == null ? "" : prompt(s.ja(), true))
                        .filter(s -> !s.isBlank()).reduce((a, b) -> a + "\n" + b).orElse("");
            }
            if (vi.isBlank()) {
                vi = previous.transcript().stream().map(s -> s.vi() == null ? "" : prompt(s.vi(), false))
                        .filter(s -> !s.isBlank()).reduce((a, b) -> a + "\n" + b).orElse("");
            }
        }
        List<JlptExamResponse.TranscriptSegment> script = ja.isBlank() && vi.isBlank() ? List.of() : List.of(
                new JlptExamResponse.TranscriptSegment(0d, local.duration(), ja, null, vi));
        boolean aligned = !local.timedScript().isEmpty();
        if (aligned) script = local.timedScript();
        return new JlptExamResponse.AudioClip(previous == null ? questionId : previous.id(),
                "QUESTION", local.url(), 0, local.duration(), script, aligned);
    }

    private static String prompt(String text, boolean japanese) {
        String clean = text.replaceAll("[（(]\\s*(?:正解\\s*[:：]|Đáp án đúng\\s*:)\\s*[1-4１-４]\\s*[）)]", "").trim();
        if (japanese) clean = localizeSpeakers(clean.split("\\n問い", 2)[0].trim());
        return clean;
    }

    private static String localizeSpeakers(String text) {
        Matcher matcher = SPEAKER.matcher(text);
        StringBuffer result = new StringBuffer();
        while (matcher.find()) {
            String role = switch (matcher.group(1).toLowerCase()) {
                case "narrator" -> "ナレーター";
                case "man" -> "男";
                case "woman" -> "女";
                default -> matcher.group(1);
            };
            String ordinal = matcher.group(2);
            matcher.appendReplacement(result, Matcher.quoteReplacement(
                    role + (ordinal.isBlank() ? "" : " " + ordinal) + ": "));
        }
        matcher.appendTail(result);
        return result.toString();
    }

    private Map<String, LocalClip> load(String exam) {
        String level = exam.substring(0, 2);
        String base = "static/audio/JLPT/" + level + "/" + exam + "/";
        ClassPathResource resource = new ClassPathResource(base + exam + "_audio_mapping.json");
        if (!resource.exists()) return Map.of();
        try (var input = resource.getInputStream()) {
            JsonNode mapping = mapper.readTree(input);
            if (!exam.equals(mapping.path("exam").asText())) throw new IOException("Exam code mismatch");
            JsonNode timed = mapper.createObjectNode();
            ClassPathResource transcriptResource = new ClassPathResource(base + "local_transcripts.json");
            if (transcriptResource.exists()) {
                try (var transcriptInput = transcriptResource.getInputStream()) {
                    JsonNode document = mapper.readTree(transcriptInput);
                    if (!exam.equals(document.path("exam").asText())) throw new IOException("Transcript exam mismatch");
                    timed = document.path("questions");
                }
            }
            Map<String, LocalClip> result = new LinkedHashMap<>();
            for (JsonNode mondai : mapping.path("mondai")) {
                for (JsonNode question : mondai.path("questions")) {
                    int m = mondai.path("number").asInt(), q = question.path("number").asInt();
                    String file = "Mondai" + m + "/" + q + ".mp3";
                    double duration = question.path("durationMs").asDouble() / 1000;
                    if (!file.equals(question.path("file").asText()) || duration <= 0
                            || !new ClassPathResource(base + file).exists()) {
                        throw new IOException("Invalid local clip: " + file);
                    }
                    List<JlptExamResponse.TranscriptSegment> segments = new ArrayList<>();
                    for (JsonNode segment : timed.path(m + ":" + q).path("segments")) {
                        double start = segment.path("start").asDouble(), end = segment.path("end").asDouble();
                        if (start < 0 || end <= start || end > duration + 0.001) {
                            throw new IOException("Invalid transcript timestamp: " + file);
                        }
                        segments.add(new JlptExamResponse.TranscriptSegment(start, end,
                                localizeSpeakers(segment.path("ja").asText("")), segment.path("furigana").asText(null),
                                segment.path("vi").asText(null)));
                    }
                    if (result.put(m + ":" + q, new LocalClip("/audio/JLPT/" + level + "/" + exam + "/" + file, duration,
                            prompt(question.path("scriptJa").asText(""), true),
                            prompt(question.path("scriptVi").asText(""), false), List.copyOf(segments))) != null) {
                        throw new IOException("Duplicate local clip: " + file);
                    }
                }
            }
            var aliases = mapping.path("questionAliases").fields();
            while (aliases.hasNext()) {
                var alias = aliases.next();
                var target = result.get(alias.getValue().asText());
                if (!alias.getKey().matches("[1-9]\\d*:[1-9]\\d*") || target == null || result.putIfAbsent(alias.getKey(), target) != null) {
                    throw new IOException("Invalid question alias: " + alias.getKey());
                }
            }
            return Map.copyOf(result);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot load local JLPT audio for " + exam, e);
        }
    }
}
